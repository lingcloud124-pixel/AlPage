export function buildGlobalColors(colors, templateType = 'light-ui') {
  const isDarkUI = templateType === 'dark-ui';

  return {
    templateType,
    primary: colors.primary,
    primaryHover: colors.primaryHover,
    alterColor: colors.alterColor,
    alterColorHoverOn: colors.alterColorHoverOn,
    primaryOpacity10: colors.primaryOpacity10 || (colors.primary + '1A'),
    primaryOpacity20: colors.primaryOpacity20 || (colors.primary + '33'),
    primaryOpacity30: colors.primaryOpacity30 || (colors.primary + '4D'),
    headerFontColor: colors.headerFont || (isDarkUI ? '#FFE4CF' : '#333333'),
    headerFontColorHover: '#ffffff',
    portalHeaderBgExtendColor: colors.alterColor,
    portalHeaderPureExtendColor: colors.alterColor,
    portalHeaderComplexBgExtendColor: colors.alterColor,
    portalHeaderComplexPureExtendColor: isDarkUI ? colors.primary : colors.alterColor,
    portalHeaderFontColor: '$header-font-color',
    portalHeaderFontColorHover: '$primary-color',
    portalHeaderSimpleBgExtendColor: isDarkUI ? '$portal-header-bg-extend-color' : colors.alterColor,
    portalHeaderSimpleFontColorHover: isDarkUI ? '$primary-color' : '#ffffff',
    portalHeaderSimpleFontColorTop: isDarkUI ? '#FFE4CF' : '#333333',
    portalHeaderSimplePureExtendColor: isDarkUI ? colors.primary : colors.alterColor,
    portalHeaderZoneBgExtendColor: colors.alterColor,
    portalHeaderZoneFontColor: isDarkUI ? '$header-font-color' : '#333333',
    portalHeaderZoneFontColorHover: isDarkUI ? '$primary-color' : '#cccccc',
    loginBgColor: colors.alterColor,
    sidebarColor: '#2A2045',
    sidebarIconColor: colors.primaryHover,
    sidebarIconColorHover: '#ffffff',
    sidebarPanelBg: isDarkUI ? (colors.headerFont || '#FFE4CF') : '#FFFFFF',
    sidebarAccordionPanelFont: isDarkUI ? (colors.headerFont || '#FFE4CF') : '#333333',
    sidebarAccordionPanelHeaderBg: isDarkUI ? colors.primary : 'transparent',
    sidebarAccordionPanelHeaderBgOn: colors.primary,
    sidebarItemCurrentColor: isDarkUI ? '#fff' : '#333333',
    sidebarItemCurrentHex: colors.alterColor,
    searchFontColor: isDarkUI ? (colors.headerFont || '$header-font-color') : colors.headerFont,
    searchInputBorderColor: colors.headerFont || colors.primary,
    searchPlaceholdFontColor: colors.headerFont || colors.primary,
    auxiliaryGray: '#999999',
    auxiliaryGrayDark: '#666666',
    bodyBgColor: '#F8F8F8',
    hoverBgColor: '#f8f8f8',
    linkText: colors.primary,
    linkTextOn: colors.alterColor,
    borderColor: '#eeeeee',
    borderIconColor: '#eeeeee',
    loginPrimaryColor: colors.primaryHover,
    loginPrimaryHover: colors.headerFont || '#ffffff',
    lightPrimaryColorHover: isDarkUI ? '$primary-color-hover' : '$primary-color',
    singleHeaderBgExtendColor: isDarkUI ? '$portal-header-bg-extend-color' : colors.alterColor,
    singleHeaderFontColor: isDarkUI ? '$header-font-color' : '#333333',
    singleHeaderFontColorHover: isDarkUI ? '$primary-color' : '#ffffff',
    tlayoutHeaderBgExtendColor: isDarkUI ? '$portal-header-bg-extend-color' : colors.alterColor,
    tlayoutHeaderFontColor: isDarkUI ? '$header-font-color' : '#333333',
    tlayoutHeaderFontColorHover: isDarkUI ? '$primary-color' : '#cccccc',
  };
}
